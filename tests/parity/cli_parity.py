# `clean` runs cpptraj; the cases use a stand-in (CPPTRAJ_FAKE) that reads the script MDATK wrote
# (-i FILE), copies the topology and the first trajectory to the files the script names and writes a
# one-model PDB, printing cpptraj-like progress; variants that fail (exit 3) or write nothing.
CPPTRAJ_FAKE = r"""#!/bin/sh
script="$2"
parm=$(sed -n 's/^parm "\(.*\)"$/\1/p' "$script")
traj=$(sed -n 's/^trajin "\([^"]*\)".*/\1/p' "$script" | head -n 1)
for out in $(sed -n 's/.*parmout "\([^"]*\)".*/\1/p; s/^parmwrite out "\([^"]*\)"$/\1/p' "$script"); do
  cp "$parm" "$out"
done
cp "$traj" "$(sed -n 's/^trajout "\([^"]*\)" netcdf$/\1/p' "$script")"
printf 'MODEL        1\nENDMDL\nEND\n' > "$(sed -n 's/^trajout "\([^"]*\)" pdb onlyframes 1$/\1/p' "$script")"
# one write: the reader gets the output in one chunk, so progress and lines come in a fixed order
printf "CPPTRAJ: Trajectory Analysis. (stand-in of tests/parity/cli_parity.py)\nINPUT: Reading input from '%s'\n 50%% Complete.\n100%% Complete.\n" "$script"
"""
CPPTRAJ_FAILS = "#!/bin/sh\necho 'Error: stand-in failure' >&2\nexit 3\n"
CPPTRAJ_SILENT = "#!/bin/sh\necho 'nothing written'\n"
CLEAN_SETUP = {"cpptraj-fake": CPPTRAJ_FAKE, "cpptraj-fails": CPPTRAJ_FAILS, "cpptraj-silent": CPPTRAJ_SILENT}
CLEAN_EXE = list(CLEAN_SETUP)
NO_CPPTRAJ = {**NO_CONDA, "AMBERHOME": "", "PATH": "/usr/bin:/bin"}
FAKE = ["--cpptraj", "./cpptraj-fake"]


def clean_case(name, argv, before=None, env=None, exit_only=False):
    return case(name, ["clean", *argv], DEMO, CLEAN_SETUP, before=before, env=env or NO_CPPTRAJ,
                executable=CLEAN_EXE, exit_only=exit_only)


