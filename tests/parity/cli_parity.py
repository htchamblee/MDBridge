def child(mdatk, jobs_file, results_file):
    import logging
    import warnings

    warnings.filterwarnings("ignore")
    sys.path.insert(0, os.path.abspath(mdatk))
    sys.path.insert(0, HERE)
    import independent_tables

    independent_tables.apply()
    import improvements_periodic

    improvements_periodic.apply_mdatk()  # MDBridge's periodic geometry (before the analysis items)
    # MDBridge's deliberate differences in the selections (improvements_selections.py)
    import improvements_selections
    from mdatk import selections

    improvements_selections.patch_mdatk(selections)
    from mdatk.analysis import base

    improvements_selections.patch_mdatk_analysis_base(base)
    import improvements_analyses

    improvements_analyses.apply_mdatk()  # the analysis improvements (docs/DIFFERENCES.md)

    import improvements_cli

    improvements_cli.apply()  # MDBridge's documented improvements (docs/DIFFERENCES.md)
    import matplotlib

    matplotlib.use("Agg")
    matplotlib.rcdefaults()  # no matplotlibrc of the machine (/etc/matplotlibrc may name other fonts)
    import improvements_fonts

    improvements_fonts.apply()  # MDBridge's figure fonts (FONT-01 ... FONT-03)
    import improvements_render
    from mdatk import density

    map_level = density.map_level
    improvements_render.apply_mdatk()  # MDBridge's rendering improvements (render, charts, preview)
    improvements_fonts.apply_mdatk()  # residue tick labels in the sequence font (FONT-03)
    # RN-33 (the structure view's finite-voxel contour level) is the structure panel's; `density
    # info` reports MDATK's level_2sigma (no render case shows a map)
    density.map_level = map_level
    import improvements_citations

    improvements_citations.apply_mdatk()  # MDBridge's citations (CIT-01, CIT-02; params and step logs)
    import improvements_chem

    improvements_chem.apply_cli()  # the chem layer's improvements (CH-01 ... CH-15, D7, D11 ... D13)
    import improvements_workflow

    improvements_workflow.apply_cli()  # the workflow layer's (WG-01 ... WG-21, D3, D6, D9, D11, D13, D14)
    from mdatk import cli
    import citations_command

    def run(argv):
        out, err = io.StringIO(), io.StringIO()
        root = logging.getLogger()
        for handler in list(root.handlers):  # basicConfig() in cli.main binds the current sys.stderr
            root.removeHandler(handler)
        old = sys.stdout, sys.stderr
        sys.stdout, sys.stderr = out, err
        try:
            # `citations` is MDBridge's (D14): its specification on MDATK's functions
            code = citations_command.main(argv[1:], cli) if argv[:1] == ["citations"] else cli.main(argv)
        except SystemExit as exc:  # argparse
            code = exc.code if isinstance(exc.code, int) else 1
        except BaseException:  # noqa: BLE001 - an uncaught exception: Python prints it, exit 1
            traceback.print_exc()
            code = 1
        finally:
            sys.stdout, sys.stderr = old
        return [code, out.getvalue(), err.getvalue().replace(NETCDF_NOTICE, "").replace(NETCDF_WRITER_NOTICE, "")]

    with open(jobs_file, encoding="utf-8") as fh:
        jobs = json.load(fh)
    results = []
    start = os.getcwd()
    for argv, folder, before, env, *rest in jobs:
        saved, saved_argv = dict(os.environ), sys.argv
        os.environ.update(env)
        os.chdir(folder)
        try:
            set_argv = rest and rest[0]  # the chem commands log their command line (sys.argv) in the step log
            exits = []
            for b in before:
                sys.argv = ["mdatk", *b] if set_argv else saved_argv
                exits.append(run(b)[0])
            sys.argv = ["mdatk", *argv] if set_argv else saved_argv
            results.append([*run(argv), exits])
        finally:
            sys.argv = saved_argv
            os.chdir(start)
            os.environ.clear()
            os.environ.update(saved)
    with open(results_file, "w", encoding="utf-8") as fh:
        json.dump(results, fh)


def run_mdatk(cases, root, mdatk, python):
    jobs = []
    for c in cases:
        folder = os.path.join(root, "mdatk", c["name"])
        prepare(c, folder)
        jobs.append([c["argv"], folder, c["before"], case_env(c, folder), bool(c.get("needs"))])
    jobs_file, results_file = os.path.join(root, "jobs.json"), os.path.join(root, "results.json")
    with open(jobs_file, "w", encoding="utf-8") as fh:
        json.dump(jobs, fh)
    subprocess.run([python, "-I", "-B", os.path.abspath(__file__), "--child", mdatk, jobs_file, results_file],
                   check=True)
    with open(results_file, encoding="utf-8") as fh:
        outputs = json.load(fh)
    results = {}
    for c, job, (code, stdout, stderr, before) in zip(cases, jobs, outputs):
        if any(before):
            raise RuntimeError(f"{c['name']}: a command line run before the case failed in MDATK ({before})")
        for old, new in NAMING:
            stdout, stderr = stdout.replace(old, new), stderr.replace(old, new)
        stdout, stderr = improvements_cli.improve_text(stdout), improvements_cli.improve_text(stderr)
        stderr = improved_map_error(c, stderr)
        res = result(c, job[1], code, stdout, stderr, before)
        if TRACEBACK in stderr:
            # MDATK crashed (an exception its main() does not catch: MemoryError, zlib.error,
            # AttributeError ...): Python prints the traceback and exits with 1, MDBridge reports
            # "error: <message>"; the exit status, stdout and files are compared
            res["stderr"] = None
            res["mdatk_crash"] = stderr.strip().splitlines()[-1]
        # MDBridge prints the readers' warnings (LD-03, LD-05) and words some errors itself (LD-06)
        res = improvements_readers_pdb.adjust_cli(c["name"], c["argv"], res)
        results[c["name"]] = res
    return results


def improved_map_error(case_, stderr):
    """`density info`: MapError texts as mrc.cpp words them (CLI-04: always the path, byte-order
    problems named as such)."""
    if case_["argv"][:2] != ["density", "info"] or not stderr.startswith("error: ") or stderr.count("\n") != 1:
        return stderr
    path = case_["argv"][2]
    source = case_["inputs"].get(path)
    if source is None:
        return stderr
    with open(os.path.join(DATA, source), "rb") as fh:
        message = improvements_cli.improve_map_message(stderr[len("error: "):-1], fh.read(), path)
    if not message.startswith(path + ": ") and not message.startswith("[Errno"):
        message = f"{path}: {message}"
    return f"error: {message}\n"


def run_mdbridge(cases, root, exe):
    out = {}
    for c in cases:
        folder = os.path.join(root, "mdbridge", c["name"])
        prepare(c, folder)
        env = dict(os.environ, APPIMAGE_EXTRACT_AND_RUN="1", **case_env(c, folder))
        before = [subprocess.run([*exe, *b], cwd=folder, capture_output=True, env=env, timeout=300).returncode
                  for b in c["before"]]
        run = subprocess.run([*exe, *c["argv"]], cwd=folder, capture_output=True, env=env, timeout=300)
        decode = lambda b: b.decode("utf-8", "surrogateescape")  # noqa: E731
        out[c["name"]] = result(c, folder, run.returncode, decode(run.stdout), decode(run.stderr), before)
    return out


