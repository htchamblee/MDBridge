def with_work(text, folder):
    return text.replace("{work}", os.path.abspath(folder))


def prepare(case_, folder):
    os.makedirs(folder)
    for dest, source in case_["inputs"].items():
        target = os.path.join(folder, dest)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copyfile(os.path.join(DATA, source), target)
    for dest, text in case_["setup"].items():
        target = os.path.join(folder, dest)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(with_work(text, folder))
    for dest in case_["executable"]:
        target = os.path.join(folder, dest)
        os.chmod(target, os.stat(target).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def case_env(case_, folder):
    return {k: with_work(v, folder).replace("{pubchem}", PUBCHEM["url"]) for k, v in case_["env"].items()}


def normalise(text, folder):
    for path in {os.path.realpath(folder), os.path.abspath(folder)}:
        text = text.replace(path, "{work}")
    text = PROGRAM_RE.sub("{program} - output directory", FINISHED_RE.sub("Finished in {seconds} s", text))
    text = GENERATED_RE.sub("# Generated by MDBridge {version} on {time}", CLEANED_KEY_RE.sub("{key}", text))
    return MANIFEST_RE.sub("{manifest}", CACHE_KEY_RE.sub("-{key}", STAMP_RE.sub("{stamp}", text)))


def normalise_name(rel, folder):
    """A file's relative path as compared: {work}, {stamp}, the cache's names."""
    rel = normalise(rel, folder)
    return CACHE_ENTRY_RE.sub(r"-{key}.\1", rel)


def collect(case_, folder, paths=None):
    """Files left in the folder (inputs included when the run changed them): compared path -> [bytes]
    (several for the cache entries of one analysis with different keys)."""
    out = {}
    for here, _dirs, names in os.walk(folder):
        for name in names:
            if OFFSETS_RE.match(name):
                continue
            full = os.path.join(here, name)
            rel = os.path.relpath(full, folder).replace(os.sep, "/")
            if rel.startswith(USER_CACHE):
                continue
            with open(full, "rb") as fh:
                data = fh.read()
            if rel in case_["inputs"]:
                continue  # copies of test data: never written by these commands
            if rel in case_["setup"] and data == with_work(case_["setup"][rel], folder).encode("utf-8"):
                continue
            key = normalise_name(rel, folder)
            if key in out and not is_cache_file(key):
                raise RuntimeError(f"{case_['name']}: {rel} and another file are both compared as {key}")
            out.setdefault(key, []).append(data)  # cache entries of one analysis with several keys
            if paths is not None:
                paths[key] = full
    return dict(sorted(out.items()))


def is_cache_file(rel):
    return rel.endswith("{manifest}") or rel.endswith("-{key}.npz") or rel.endswith("-{key}.json")


def masked_cache_json(value, folder, top=True):
    """A cache manifest or entry description with what legitimately differs masked."""
    if isinstance(value, dict):
        out = {}
        for k, v in value.items():
            if top and k in ("mdatk_version", "mdbridge_version"):
                out["version"] = "{version}"
            elif top and k == "project":
                out[k] = "{project}"
            elif top and k in ("updated", "created"):
                out[k] = "{time}"
            elif k in ("key", "cleaning_key") and isinstance(v, str):  # cleaning_key: it hashes mtimes too
                out[k] = "{key}"
            elif k == "mtime_ns":
                out[k] = 0
            elif k == "file" and isinstance(v, str):
                out[k] = normalise_name(v, folder)
            else:
                out[k] = masked_cache_json(v, folder, False)
        if "all_entries" in out and isinstance(out["all_entries"], list):
            out["all_entries"] = sorted(out["all_entries"], key=lambda e: json.dumps(e, sort_keys=True))
        return out
    if isinstance(value, list):
        return [masked_cache_json(v, folder, False) for v in value]
    if isinstance(value, str):
        return normalise(value, folder)
    return value


def json_float(x):
    return x if math.isfinite(x) else ("nan" if math.isnan(x) else ("inf" if x > 0 else "-inf"))


def read_npz(data):
    """[[name, dtype, shape, flat values], ...] of a .npz archive (C order arrays of NPY_TYPES / <U)."""
    out = []
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        for member in archive.namelist():
            raw = archive.read(member)
            assert raw[:6] == b"\x93NUMPY", member
            if raw[6] == 1:
                (length,), start = struct.unpack("<H", raw[8:10]), 10
            else:
                (length,), start = struct.unpack("<I", raw[8:12]), 12
            header = ast.literal_eval(raw[start:start + length].decode("latin1"))
            assert not header["fortran_order"], member
            body = raw[start + length:]
            dtype, shape = header["descr"], list(header["shape"])
            count = math.prod(shape)
            if dtype.startswith("<U"):
                width = int(dtype[2:])
                values = [body[i * 4 * width:(i + 1) * 4 * width].decode("utf-32-le").rstrip("\0")
                          for i in range(count)]
            else:
                values = list(struct.unpack(f"<{count}{NPY_TYPES[dtype]}", body[:count * struct.calcsize(
                    NPY_TYPES[dtype])]))
                if dtype in ("<f8", "<f4"):
                    values = [json_float(v) for v in values]
            out.append([member[:-4] if member.endswith(".npy") else member, dtype, shape, values])
    return out


def file_entry(rel, data, folder, mask=None, limit=LIMIT):
    """mask: a further normalisation of a text file's text (before a large file is hashed); limit: the
    largest text kept as text (None: any; the fitted cases' files are compared with a tolerance)."""
    if rel.endswith("/" + CLEAN_MARKER):  # clean's marker: as JSON, time / version / project masked
        return {"json": masked_cache_json(json.loads(data.decode("utf-8")), folder)}
    if is_cache_file(rel):
        if rel.endswith(".npz"):
            # the flat values as one line of JSON text (compact; the C++ test parses it)
            return {"npz": [[name, dtype, shape, json.dumps(values, ensure_ascii=False, separators=(",", ":"))]
                            for name, dtype, shape, values in read_npz(data)]}
        return {"json": masked_cache_json(json.loads(data.decode("utf-8")), folder)}
    if limit is None and rel.endswith(".mrc") and len(data) >= 1024:
        # a fitted case's map (`density simulate --placed` after a fit): its header, compared with the
        # fit's tolerance
        return {"map": map_summary(data)}
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return {"sha256": hashlib.sha256(data).hexdigest(), "size": len(data)}
    text = SAVED_RE.sub("saved = {time}", normalise(text, folder))
    if mask is not None:
        text = mask(text)
    if limit is None or len(text.encode("utf-8")) <= limit:
        return {"text": text}
    raw = text.encode("utf-8")
    return {"sha256": hashlib.sha256(raw).hexdigest(), "size": len(raw)}


def map_summary(data):
    """An MRC file's header as text: grid, start, cell, axis order, minimum / maximum / mean, origin
    (tests/cli/test_commands.cpp mapSummary writes the same)."""
    w = struct.unpack("<10i6f3i3f", data[:88])
    origin = struct.unpack("<3f", data[196:208])
    return ("grid %d %d %d mode %d start %d %d %d sampling %d %d %d cell %.4f %.4f %.4f axes %d %d %d "
            "min %.6f max %.6f mean %.6f origin %.4f %.4f %.4f"
            % (*w[0:10], *w[10:13], *w[16:19], *w[19:22], *origin))


def mp4_info(path):
    """What ffprobe reports about a video, without the codec name (RN-07), and whether moov comes
    before mdat (faststart)."""
    probe = subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-show_entries",
                            "stream=codec_type,width,height,pix_fmt,r_frame_rate,avg_frame_rate,time_base,"
                            "nb_read_frames:format=format_name,nb_streams", "-of", "json", path],
                           capture_output=True, text=True, check=True)
    data = json.loads(probe.stdout)
    boxes = []
    with open(path, "rb") as fh:
        while True:
            head = fh.read(8)
            if len(head) < 8:
                break
            size, kind = struct.unpack(">I4s", head)
            if size == 1:
                size = struct.unpack(">Q", fh.read(8))[0]
                fh.seek(size - 16, 1)
            else:
                fh.seek(size - 8, 1)
            boxes.append(kind.decode("latin-1"))
            if size == 0:
                break
    streams = sorted((dict(sorted(st.items())) for st in data.get("streams", [])), key=json.dumps)
    return {"streams": streams, "format": dict(sorted(data.get("format", {}).items())),
            "faststart": "moov" in boxes and "mdat" in boxes and boxes.index("moov") < boxes.index("mdat")}


def svg_points(value, unit):
    return round(float(value) * {"pt": 1.0, "in": 72.0, "mm": 72.0 / 25.4, "cm": 72.0 / 2.54, "px": 0.75, "": 0.75}[unit], 3)


def render_file_entry(rel, data, full, folder):
    """A render case's file: images by format and size, videos by metadata, the params log by its
    run's outputs and time stamp, the rest as file_entry."""
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return {"png": list(struct.unpack(">II", data[16:24]))}
    if data[:3] == b"\xff\xd8\xff":
        return {"jpeg": True}
    if data[:4] in (b"II*\0", b"MM\0*"):
        return {"tiff": True}
    if data[:5] == b"%PDF-":
        m = re.search(rb"/MediaBox *\[ *([0-9. ]+?) *\]", data)
        return {"pdf": [round(float(v), 3) for v in m.group(1).split()] if m else None}
    if data[:4] == b"%!PS":
        m = re.search(rb"%%BoundingBox: *([0-9 .-]+)", data)
        return {"ps": data[:40].startswith(b"%!PS-Adobe-3.0 EPSF") and "eps" or "ps",
                "bbox": [round(float(v)) for v in m.group(1).split()] if m else None}
    if b"<svg" in data[:4000]:
        m = re.search(rb'<svg[^>]*?width="([0-9.]+)(pt|in|mm|cm|px|)"[^>]*?height="([0-9.]+)(pt|in|mm|cm|px|)"', data,
                      re.S)
        return {"svg": [svg_points(m.group(1), m.group(2).decode()), svg_points(m.group(3), m.group(4).decode())]
                if m else None}
    if rel.endswith(".mp4"):
        return {"mp4": mp4_info(full)}
    if rel.endswith("MDATK_params_log.toml"):
        import tomllib

        run = tomllib.loads(data.decode("utf-8")).get("run", {})
        outputs = json.loads(normalise(json.dumps(run.get("outputs"), ensure_ascii=False), folder))
        return {"params_log": {"outputs": outputs, "timestamp": run.get("timestamp") and normalise(run["timestamp"], folder)}}
    # the step log's time and duration masked, in large project files too (the demo's)
    return file_entry(rel, data, folder,
                      lambda text: LOG_DURATION_RE.sub("duration_s = 0.0", LOG_TIME_RE.sub("time = {time}", text)))


def written_entry(rel, datas, folder, mask=None, limit=LIMIT):
    """file_entry, or {"several": [file_entry, ...]} (in a fixed order) for several cache entries."""
    if len(datas) == 1:
        return file_entry(rel, datas[0], folder, mask, limit)
    return {"several": sorted((file_entry(rel, d, folder, mask, limit) for d in datas),
                              key=lambda e: json.dumps(e, sort_keys=True))}


def step_log_mask(text):
    """The step log's time and duration masked."""
    return LOG_DURATION_RE.sub("duration_s = 0.0", LOG_TIME_RE.sub("time = {time}", text))


WSTAMP_RE = re.compile(r"(?<![0-9])20\d{6}-\d{4}(?![0-9])")


def workflow_mask(case_):
    """The workflow cases' texts (WORKFLOW): improvements_workflow.mask (D11: the version after the program's
    name, dates), with "wstamp" the plan's time stamp from the clock; None for other cases."""
    if case_["argv"][:1] != ["workflow"]:
        return None
    import improvements_workflow

    def mask(text):
        text = improvements_workflow.mask(text)
        return WSTAMP_RE.sub("{wstamp}", text) if case_.get("wstamp") else text
    return mask


def result(case_, folder, code, stdout, stderr, before):
    paths = {}
    files = collect(case_, folder, paths)
    # results that hold absolute paths or OS error texts, or read a project file's paths: defined on
    # Linux only (the C++ test skips them on Windows). The cache manifest's path that analyze prints
    # and the paths in cache files are compared on Windows too (the C++ test normalises their form).
    texts = [stderr, *(data[0].decode("utf-8", "replace") for rel, data in files.items() if not is_cache_file(rel))]
    if case_["argv"][:1] != ["analyze"]:
        texts.append(stdout)
    if case_.get("render"):
        written = {rel: (written_entry(rel, data, folder) if is_cache_file(rel) or len(data) != 1
                         else render_file_entry(rel, data[0], paths[rel], folder))
                   for rel, data in files.items()}
    else:
        # the chem cases (needs): the step log's time masked; fitted ones: texts kept whole
        mask = step_log_mask if case_.get("needs") else None
        wf_mask = workflow_mask(case_)
        if wf_mask:  # the workflow cases: also D11's version and dates (and "wstamp") in texts and names
            mask = lambda text: wf_mask(step_log_mask(text))  # noqa: E731
            files = {wf_mask(rel): data for rel, data in files.items()}
            stdout, stderr = wf_mask(stdout), wf_mask(stderr)
        limit = None if case_.get("fitted") is not None else LIMIT
        written = {rel: written_entry(rel, data, folder, mask, limit) for rel, data in files.items()}
    return {"exit": code, "stdout": normalise(stdout, folder), "stderr": normalise(stderr, folder),
            "written": written,
            "before_exits": before,
            "posix_only": any("{work}" in normalise(t, folder) for t in texts) or "[Errno" in stderr
            or any(a in ("-p", "--project", "--params") for a in case_["argv"]) or bool(case_["env"])}


