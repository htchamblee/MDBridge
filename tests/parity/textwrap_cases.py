"""Write test cases for MDBridge's port of Python's textwrap.wrap (and str.splitlines).

    python tests/parity/textwrap_cases.py MDATK_CHECKOUT OUT.toml

Project-file comments are wrapped with textwrap.wrap(text, 98), so the C++ port must break lines
exactly as Python does. The cases are string literals of MDATK's sources (help texts, messages)
plus edge cases (hyphenation, em-dashes, long words, tabs, non-ASCII), each wrapped at several
widths by the running Python.
"""

from __future__ import annotations

import ast
import hashlib
import json
import os
import sys
import textwrap

WIDTHS = (98, 31, 8)
SYNTHETIC = [
    "",
    "   ",
    "one",
    "a self-contained, well-known command-line option",
    "x-ray co-ordinates of a non-Watson-Crick pair: G-U wobble, A-minor, a-b-c, ab-c, a-bc, -leading, trailing-",
    "pre--post and well--known -- spaced em--dash, dash---triple, end--",
    "an extraordinarily-long-hyphenated-word-that-cannot-fit-on-a-single-short-line-at-all and more words",
    "Supercalifragilisticexpialidocious" * 4,
    "path/to/a/very/long/file/name/that/has/no/spaces/at/all/and/must/be/broken/somewhere.mdatk.toml",
    "tabs\there\tand\tthere, and a newline\nin the middle, a vertical\x0btab and form\x0cfeed",
    "Mg²⁺ ions, 5 Å cutoff, ψ-angle, naïve café, 🧬 helix, H₂O, 90°, ±0.5, x×y, “quoted”, — dash — and…",
    "numbers 1-2 3-4-5 v1.2-rc3 A:1-40, 45, B:5-30 and 0.5-1.0",
    "'quoted' \"double\" (paren) [bracket] {brace} a/b a\\b a_b a.b a,b a?b a!b a&b",
    "word " * 40,
    "  leading and trailing spaces  ",
]


def literals(root: str) -> list[str]:
    found: set[str] = set()
    for folder, _dirs, files in os.walk(os.path.join(root, "mdatk")):
        for name in files:
            if not name.endswith(".py"):
                continue
            with open(os.path.join(folder, name), encoding="utf-8") as fh:
                tree = ast.parse(fh.read())
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, str):
                    text = node.value
                    if 30 <= len(text) <= 600 and " " in text:
                        found.add(text)
    # a fixed, spread-out subset
    return sorted(found, key=lambda t: hashlib.sha256(t.encode()).hexdigest())[:300]


def toml_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # JSON escapes are valid TOML basic-string escapes


def main(argv=None) -> int:
    root, out = (argv or sys.argv[1:])[:2]
    lines = ["# Generated by tests/parity/textwrap_cases.py with Python "
             f"{sys.version.split()[0]}; expected results of textwrap.wrap and str.splitlines.", ""]
    for text in SYNTHETIC + literals(root):
        for width in WIDTHS:
            lines += ["[[wrap]]", f"text = {toml_string(text)}", f"width = {width}",
                      "lines = [" + ", ".join(toml_string(x) for x in textwrap.wrap(text, width)) + "]", ""]
        lines += ["[[splitlines]]", f"text = {toml_string(text)}",
                  "lines = [" + ", ".join(toml_string(x) for x in text.splitlines()) + "]", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
