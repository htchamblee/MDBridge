"""Write the name tables of MDAnalysis' selection language that src/core/atom_selection.cpp uses.

    /opt/mdbridge-venv/bin/python tools/gen_selection_tables.py

The macros protein, nucleic, water, backbone, nucleicbackbone, nucleicbase and nucleicsugar select
by fixed lists of residue and atom names, and the errors of "prop" and "same" list the properties
MDAnalysis knows. The lists are read from the installed MDAnalysis (2.11.0, which MDATK v0.0.4.1
runs) and written as data to src/core/selection_tables.inc, which is committed, so a build needs
no Python.
"""

from __future__ import annotations

import json
import os
import sys
import warnings

warnings.filterwarnings("ignore")

import MDAnalysis  # noqa: E402
from MDAnalysis.core import selection  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "core", "selection_tables.inc")


def literal(text: str) -> str:
    if not text.isascii():
        sys.exit(f"non-ASCII table entry {text!r}")
    return json.dumps(text)


def names(var: str, values) -> list[str]:
    items = sorted(values)
    lines = [f"constexpr std::string_view {var}[] = {{"]
    line = "   "
    for item in items:
        piece = f" {literal(item)},"
        if len(line) + len(piece) > 100:
            lines.append(line)
            line = "   "
        line += piece
    lines.append(line)
    lines.append("};")
    return lines


def long_literal(var: str, text: str) -> list[str]:
    pieces = [text[i:i + 80] for i in range(0, len(text), 80)]
    return [f"constexpr std::string_view {var} ="] + [f"    {literal(p)}" for p in pieces[:-1]] + [
        f"    {literal(pieces[-1])};"]


def main() -> None:
    if MDAnalysis.__version__ != "2.11.0":
        print(f"warning: MDAnalysis {MDAnalysis.__version__}, the tables are for 2.11.0", file=sys.stderr)
    props = selection.PropertySelection.props
    same = selection.SameSelection.prop_trans
    out = [
        f"// Generated by tools/gen_selection_tables.py from MDAnalysis {MDAnalysis.__version__}; do not edit.",
        "",
    ]
    out += names("kProteinResnames", selection.ProteinSelection.prot_res)
    out += names("kNucleicResnames", selection.NucleicSelection.nucl_res)
    out += names("kWaterResnames", selection.WaterSelection.water_res)
    out += names("kBackboneNames", selection.BackboneSelection.bb_atoms)
    out += names("kNucleicBackboneNames", selection.NucleicBackboneSelection.bb_atoms)
    out += names("kNucleicBaseNames", selection.BaseSelection.base_atoms)
    out += names("kNucleicSugarNames", selection.NucleicSugarSelection.sug_atoms)
    # property names as the parser sees them (the None entry is a token that a string never equals)
    out += names("kSameNames", [k for k in same if k is not None])
    out.append("// prop <name>: the attribute it reads")
    out.append("constexpr std::pair<std::string_view, std::string_view> kPropAttributes[] = {")
    for k, v in props.items():
        if k is not None:
            out.append(f"    {{{literal(k)}, {literal(v)}}},")
    out.append("};")
    out += long_literal("kPropNamesRepr", repr(list(props.keys())))
    out += long_literal("kSameNamesRepr", str(same.keys()))
    with open(OUTPUT, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
