"""Write the tables of src/io/pdb_tables.inc: Python's str.upper() and str.isalpha() data, and the
name / mass tables of MDAnalysis that its PDB parser, guessers and PDB writer use.

    /opt/mdbridge-venv/bin/python -I tools/gen_pdb_tables.py

Python 3.13 (Unicode 15.1) and MDAnalysis 2.11.0 (which MDATK v0.0.4.1 runs). The tables are data
read from the running Python and the installed MDAnalysis; the output is committed, so a build
needs no Python.
"""

from __future__ import annotations

import os
import re
import sys
import warnings

warnings.filterwarnings("ignore")

from MDAnalysis.coordinates.PDB import PDBWriter  # noqa: E402
from MDAnalysis.guesser import tables  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "io", "pdb_tables.inc")


def literal(text: str) -> str:
    if not text.isascii():
        sys.exit(f"non-ASCII table entry {text!r}")
    return '"' + text + '"'


def upper_tables():
    """(first, last, step, delta) runs of single-character mappings and the expanding ones."""
    runs, special = [], []
    for c in range(0x110000):
        u = chr(c).upper()
        if u == chr(c):
            continue
        if len(u) > 1:
            special.append((c, u))
            continue
        d = ord(u) - c
        if runs:
            first, last, step, delta = runs[-1]
            if delta == d and step == 0 and c - last in (1, 2):
                runs[-1] = [first, c, c - last, d]
                continue
            if delta == d and step and c - last == step:
                runs[-1][1] = c
                continue
        runs.append([c, c, 0, d])
    return runs, special


def word_not_alpha():
    """Ranges of characters that re's \\w matches but that are neither '_', alphabetic nor \\d."""
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    ranges = []
    for c in range(0x110000):
        ch = chr(c)
        if word.match(ch) and ch != "_" and not ch.isalpha() and not digit.match(ch):
            if ranges and ranges[-1][1] == c - 1:
                ranges[-1][1] = c
            else:
                ranges.append([c, c])
    return ranges


def utf8_literal(text: str) -> str:
    return '"' + "".join(f"\\x{b:02x}" for b in text.encode()) + '"'


def main():
    runs, special = upper_tables()
    out = [
        "// Generated by tools/gen_pdb_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} and MDAnalysis "
        f"{__import__('MDAnalysis').__version__}; do not edit.",
        "",
        "// str.upper(): runs {first, last, step, delta} of characters mapped to character + delta",
        "struct UpperRun {",
        "    char32_t first;",
        "    char32_t last;",
        "    std::int32_t step;",
        "    std::int32_t delta;",
        "};",
        "constexpr UpperRun kUpperRuns[] = {",
    ]
    for first, last, step, delta in runs:
        out.append(f"    {{0x{first:x}, 0x{last:x}, {step}, {delta}}},")
    out += ["};", "", "// str.upper() of the characters that expand (UTF-8)",
            "struct UpperSpecial {", "    char32_t code;", "    const char* upper;", "};",
            "constexpr UpperSpecial kUpperSpecial[] = {"]
    for code, text in special:
        out.append(f"    {{0x{code:x}, {utf8_literal(text)}}},")
    out += ["};", "", "// \\w characters that are not '_', not str.isalpha() and not \\d",
            "constexpr std::array<char32_t, 2> kWordNotAlpha[] = {"]
    for first, last in word_not_alpha():
        out.append(f"    {{0x{first:x}, 0x{last:x}}},")
    out += ["};", "", "// MDAnalysis.guesser.tables.atomelements",
            "constexpr std::pair<std::string_view, std::string_view> kAtomElements[] = {"]
    for key, value in tables.atomelements.items():
        out.append(f"    {{{literal(key)}, {literal(value)}}},")
    out += ["};", "", "// MDAnalysis.guesser.tables.elements", "constexpr std::string_view kGuessElements[] = {"]
    out.append("    " + ", ".join(literal(e) for e in tables.elements) + ",")
    out += ["};", "", "// MDAnalysis.guesser.tables.masses",
            "constexpr std::pair<std::string_view, double> kMasses[] = {"]
    for key, value in tables.masses.items():
        out.append(f"    {{{literal(key)}, {float(value)!r}}},")
    out += ["};", "", "// MDAnalysis.guesser.tables.SYMB2Z (the element symbols)",
            "constexpr std::string_view kElementSymbols[] = {"]
    keys = list(tables.SYMB2Z)
    for k in range(0, len(keys), 12):
        out.append("    " + ", ".join(literal(e) for e in keys[k:k + 12]) + ",")
    out += ["};", "", "// PDBWriter's atom-name alignment lists"]
    for name in ("ions", "special_hg", "special_cl"):
        values = getattr(PDBWriter, name)
        camel = "k" + "".join(part.capitalize() for part in name.split("_"))
        out.append(f"constexpr std::string_view {camel}[] = {{")
        for k in range(0, len(values), 12):
            out.append("    " + ", ".join(literal(e) for e in values[k:k + 12]) + ",")
        out.append("};")
    for name in ("include_pairs", "exclude_pairs"):
        values = getattr(PDBWriter, name)
        camel = "k" + "".join(part.capitalize() for part in name.split("_"))
        out.append(f"constexpr std::pair<std::string_view, std::string_view> {camel}[] = {{")
        for pair in values:
            out.append(f"    {{{literal(pair[0])}, {literal(pair[1])}}},")
        out.append("};")
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
