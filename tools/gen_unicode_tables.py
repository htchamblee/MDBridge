"""Write the Unicode character classes MDBridge's port of Python's textwrap needs.

    python tools/gen_unicode_tables.py

Python's regular expressions and str methods classify characters with Unicode data: textwrap
splits words with \\w and \\d, and strips with str.isspace(). The ranges generated here (from the
running Python's unicodedata) let src/core/text.cpp classify exactly as Python does; the output
src/core/unicode_tables.inc is committed, so a build needs no Python.
"""

from __future__ import annotations

import os
import re
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "core", "unicode_tables.inc")
WORD = re.compile(r"\w")
DIGIT = re.compile(r"\d")


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for code in range(0x110000):
        if predicate(chr(code)):
            if out and out[-1][1] == code - 1:
                out[-1] = (out[-1][0], code)
            else:
                out.append((code, code))
    return out


def table(name: str, items: list[tuple[int, int]]) -> list[str]:
    rows = [f"    {{0x{a:X}, 0x{b:X}}}," for a, b in items]
    return [f"inline constexpr CodeRange {name}[] = {{", *rows, "};", ""]


def main() -> int:
    lines = [
        "// Unicode character classes of Python's re (\\w, \\d) and str.isspace(). Generated by",
        f"// tools/gen_unicode_tables.py with Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}); do not edit.",
        "// Included by src/core/text.cpp inside its namespace.",
        "",
        "struct CodeRange {",
        "    char32_t first;",
        "    char32_t last;",
        "};",
        "",
        *table("kWordRanges", ranges(lambda c: WORD.match(c) is not None)),
        *table("kDigitRanges", ranges(lambda c: DIGIT.match(c) is not None)),
        *table("kSpaceRanges", ranges(str.isspace)),
    ]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
