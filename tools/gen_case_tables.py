"""Write the Unicode data of Python's str.lower() for MDBridge's port (core::pythonLower).

    python3 -I tools/gen_case_tables.py

str.lower() maps every character to its full lowercase mapping; the only mapping longer than one
character is U+0130 (to "i" + U+0307), and U+03A3 becomes final sigma (U+03C2) after a cased
character (case-ignorable ones skipped) that is not followed by another (CPython's
handle_capital_sigma). The tables are probed from the running Python's str.lower() itself:
the one-character mappings, and which characters are case-ignorable and which cased (as
handle_capital_sigma sees them). The output src/core/case_tables.inc is committed, so a build
needs no Python. MDATK v0.0.4.1 is compared with Python 3.13 (Unicode 15.1).
"""

from __future__ import annotations

import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "core", "case_tables.inc")
SIGMA = "Σ"


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for code in range(0x110000):
        if predicate(code):
            if out and out[-1][1] == code - 1:
                out[-1] = (out[-1][0], code)
            else:
                out.append((code, code))
    return out


def sigma_class(code: int) -> str:
    """'ignorable', 'cased' or '' as handle_capital_sigma classifies the character."""
    c = chr(code)
    after_digit = ("1" + c + SIGMA).lower()[-1]
    after_letter = ("A" + c + SIGMA).lower()[-1]
    if after_digit == "σ" and after_letter == "ς":
        return "ignorable"
    if after_digit == "ς" and after_letter == "ς":
        return "cased"
    assert after_digit == after_letter == "σ", hex(code)
    return ""


def main() -> int:
    mappings = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF or code in (0x130, 0x3A3):
            continue
        lower = chr(code).lower()
        if lower != chr(code):
            assert len(lower) == 1, hex(code)
            mappings.append((code, ord(lower)))
    assert "İ".lower() == "i̇"
    classes = [sigma_class(code) if not 0xD800 <= code <= 0xDFFF else "" for code in range(0x110000)]
    lines = [
        "// Unicode data of Python's str.lower(): one-character lowercase mappings (U+0130 and",
        "// U+03A3 are handled in code), case-ignorable and cased characters (final sigma).",
        f"// Generated by tools/gen_case_tables.py with Python {sys.version.split()[0]} "
        f"(Unicode {unicodedata.unidata_version}); do not edit.",
        "// Included by src/core/text.cpp inside its namespace, after unicode_tables.inc.",
        "",
        "struct CaseMapping {",
        "    char32_t code;",
        "    char32_t lower;",
        "};",
        "",
        "inline constexpr CaseMapping kLowerMappings[] = {",
    ]
    row = []
    for code, lower in mappings:
        row.append(f"{{0x{code:X}, 0x{lower:X}}},")
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines += ["};", ""]
    for name, kind in (("kCaseIgnorableRanges", "ignorable"), ("kCasedRanges", "cased")):
        lines.append(f"inline constexpr CodeRange {name}[] = {{")
        lines += [f"    {{0x{a:X}, 0x{b:X}}}," for a, b in ranges(lambda c: classes[c] == kind)]
        lines += ["};", ""]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}: {len(mappings)} mappings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
