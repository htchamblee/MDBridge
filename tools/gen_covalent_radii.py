"""Write the covalent radii of the analyses' distance bond guesser as C++ data.

    python3 -I -B tools/gen_covalent_radii.py

Reads data/sources/covalent_radii/cordero2008.tsv (Cordero et al., Dalton Trans. 2008, Table 2;
see its README) and writes src/analysis/covalent_radii.inc: the element symbol (upper case, as
core::atomElements gives it) and radius in Å per element, in order of Z. Included by
src/analysis/structure.cpp (AN-14). Deterministic; the build needs no Python.
"""

import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "data", "sources", "covalent_radii", "cordero2008.tsv")
INC = os.path.join(ROOT, "src", "analysis", "covalent_radii.inc")


def main() -> int:
    with open(SOURCE, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    lines = ["// Generated by tools/gen_covalent_radii.py from data/sources/covalent_radii/cordero2008.tsv",
             "// (Cordero et al., Dalton Trans. 2008, 2832-2838, Table 2). Do not edit.",
             "// {element (upper case), single-bond covalent radius in Angstrom}, in order of Z"]
    for row in rows:
        lines.append(f'{{"{row["symbol"].upper()}", {float(row["covalent_radius_angstrom"])!r}}},')
    os.makedirs(os.path.dirname(INC), exist_ok=True)
    with open(INC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
