"""Write MDATK's citation tables as C++ data.

    python3 -I -B tools/gen_citation_data.py MDATK_CHECKOUT

Reads REFERENCE_DATA and RESOURCE_DATA of mdatk/_citation_data.py (a checkout at v0.0.4.1; the file
is run on its own, nothing is imported from the package and nothing is written into the checkout)
with MDBridge's changes of tests/parity/improvements_citations.py applied (patch_data: CIT-01, the
software MDBridge does not use leaves the table and the superposition methods of its RMSD join it;
CIT-04, the force-field papers of the energy analysis' parameters without parm7 join it too;
docs/DIFFERENCES.md "Citations"), and writes src/core/citation_data.inc, included by
src/core/citations.cpp. The output is deterministic; the build needs no Python.
"""

from __future__ import annotations

import os
import runpy
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "src", "core", "citation_data.inc")
sys.path.insert(0, os.path.join(ROOT, "tests", "parity"))

import improvements_citations  # noqa: E402  MDBridge's citation table changes (CIT-01)
WIDTH = 100
REFERENCE_FIELDS = ("key", "text", "bibtex", "doi", "url", "verified")


def cpp_pieces(text: str) -> list[str]:
    """The escaped characters of a C++ string literal (non-ASCII as octal UTF-8 bytes)."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("".join(f"\\{b:03o}" for b in ch.encode("utf-8")))
    return out


def cpp_string(text: str, column: int, indent: int) -> str:
    """A string literal that starts at `column`, split into adjacent literals to stay in WIDTH."""
    pieces = cpp_pieces(text)
    room = WIDTH - column - 3  # quotes and a comma
    if sum(len(p) for p in pieces) <= room:
        return '"' + "".join(pieces) + '"'
    lines, current = [], ""
    width = WIDTH - indent - 3
    word = ""
    words = []
    for p in pieces:  # words end after a space or a line break
        word += p
        if p in (" ", "\\n"):
            words.append(word)
            word = ""
    if word:
        words.append(word)
    for w in words:
        parts = [w] if len(w) <= width else [p for p in cpp_pieces_of(w)]
        for p in parts:
            if len(current) + len(p) > width and current:
                lines.append(current)
                current = ""
            current += p
    lines.append(current)
    pad = " " * indent
    return "\n" + "\n".join(f'{pad}"{line}"' for line in lines)


def cpp_pieces_of(escaped: str) -> list[str]:
    """An escaped word split into escapes and single characters (escapes are never split)."""
    out, i = [], 0
    while i < len(escaped):
        if escaped[i] == "\\":
            n = 4 if escaped[i + 1].isdigit() else 2
            out.append(escaped[i:i + n])
            i += n
        else:
            out.append(escaped[i])
            i += 1
    return out


def main() -> int:
    if len(sys.argv) != 2:
        sys.exit("usage: gen_citation_data.py MDATK_CHECKOUT")
    data = runpy.run_path(os.path.join(sys.argv[1], "mdatk", "_citation_data.py"))
    references, resources = improvements_citations.patch_data(data["REFERENCE_DATA"], data["RESOURCE_DATA"])
    keys = [r["key"] for r in references]
    ids = [r["id"] for r in resources]
    # REFERENCES / RESOURCES are dicts built from the lists: repeated entries would collapse
    if len(set(keys)) != len(keys) or len(set(ids)) != len(ids):
        sys.exit("repeated reference keys or resource ids")
    for r in references:
        if set(r) - set(REFERENCE_FIELDS) or "key" not in r or "text" not in r or "bibtex" not in r:
            sys.exit(f"unexpected fields in reference {r.get('key')!r}")
    out = [
        "// Citation tables of MDATK v0.0.4.1 (mdatk/_citation_data.py: REFERENCE_DATA and",
        "// RESOURCE_DATA, in their order) with MDBridge's changes (tests/parity/improvements_citations.py:",
        "// CIT-01, CIT-04). Generated by tools/gen_citation_data.py; do not edit.",
        "// Included by src/core/citations.cpp inside its anonymous namespace.",
        "",
    ]
    for k, r in enumerate(resources):
        items = ", ".join(cpp_string(key, 0, 0) for key in r["keys"])
        line = f"inline constexpr std::string_view kResourceKeys{k}[] = {{{items}}};"
        if len(line) > WIDTH:
            line = (f"inline constexpr std::string_view kResourceKeys{k}[] = {{\n    "
                    + ",\n    ".join(cpp_string(key, 4, 4) for key in r["keys"]) + "};")
        out.append(line)
    out += ["", "inline constexpr Reference kReferences[] = {"]
    for r in references:
        out.append("    Reference{")
        for name in REFERENCE_FIELDS:
            head = f"        .{name} = "
            out.append(head + cpp_string(r.get(name, ""), len(head), 12) + ",")
        out.append("    },")
    out += ["};", "", "inline constexpr Resource kResources[] = {"]
    for k, r in enumerate(resources):
        out.append("    Resource{")
        for name in ("id", "name"):
            head = f"        .{name} = "
            out.append(head + cpp_string(r[name], len(head), 12) + ",")
        out.append(f"        .keys = kResourceKeys{k},")
        head = "        .note = "
        out.append(head + cpp_string(r.get("note", ""), len(head), 12) + ",")
        out.append("    },")
    out += ["};", ""]
    text = "\n".join(line.rstrip() for line in "\n".join(out).split("\n")) + "\n"
    with open(INC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {INC}: {len(references)} references, {len(resources)} resources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
