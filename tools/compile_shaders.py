"""Compile the Vulkan renderer's GLSL shaders to SPIR-V and write them into a C++ header.

    python tools/compile_shaders.py [--glslang PATH] [--check]

Every shader in src/render/shaders is compiled: *.vert, *.frag and *.comp (the stage comes from the
extension), ordered by name and then vertex, fragment, compute. Files *.glsl are shared code that
shaders pull in with `#include "name.glsl"` (GL_GOOGLE_include_directive); they are not compiled on
their own but their hashes are recorded too. A shader "a_b.frag" becomes the array kABFragSpirv
(std::uint32_t words) in namespace mdbridge::render::spirv.

The header (src/render/shaders/spirv.hpp) is committed, so building MDBridge needs no shader
compiler. It records the SHA-256 of every source; the test "render.shaders_up_to_date"
(cmake/CheckShaders.cmake) fails when a shader changed without running this script again.
--check writes nothing and fails when the header differs from what this script would write (the
same glslang version gives the same SPIR-V).
Needs glslangValidator (Vulkan SDK, or the glslang-tools / glslang package of a distribution).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, "src", "render", "shaders")
HEADER = os.path.join(SHADERS, "spirv.hpp")
STAGES = (".vert", ".frag", ".comp")  # compiled in this order for shaders of the same name
INCLUDES = ".glsl"


def sources() -> list[str]:
    """The shaders to compile, in header order."""
    names = [n for n in os.listdir(SHADERS) if os.path.splitext(n)[1] in STAGES]
    return sorted(names, key=lambda n: (os.path.splitext(n)[0], STAGES.index(os.path.splitext(n)[1])))


def includes() -> list[str]:
    return sorted(n for n in os.listdir(SHADERS) if n.endswith(INCLUDES))


def sha256(name: str) -> str:
    with open(os.path.join(SHADERS, name), "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def symbol(name: str) -> str:
    stem, stage = name.rsplit(".", 1)
    return "k" + "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]", stem)) + stage.capitalize() + "Spirv"


def compile_one(glslang: str, source: str, work: str) -> bytes:
    out = os.path.join(work, os.path.basename(source) + ".spv")
    subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-I" + SHADERS, "-o", out, source], check=True,
                   stdout=subprocess.DEVNULL)
    with open(out, "rb") as fh:
        return fh.read()


def words(code: bytes) -> list[str]:
    assert len(code) % 4 == 0, "SPIR-V is a sequence of 32-bit words"
    return [f"0x{int.from_bytes(code[i:i + 4], 'little'):08x}" for i in range(0, len(code), 4)]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--glslang", default=shutil.which("glslangValidator"), help="glslangValidator to use")
    parser.add_argument("--check", action="store_true", help="only compare the committed header, write nothing")
    args = parser.parse_args(argv)
    if not args.glslang:
        print("glslangValidator not found (install the Vulkan SDK or glslang-tools)", file=sys.stderr)
        return 1
    version = subprocess.run([args.glslang, "--version"], check=True, capture_output=True,
                             text=True).stdout.splitlines()[0].strip()
    lines = ["#pragma once",
             "// SPIR-V of the Vulkan renderer's shaders. Generated by tools/compile_shaders.py; do not edit.",
             f"// {version}, --target-env vulkan1.3",
             "// Sources (cmake/CheckShaders.cmake compares these hashes with the shaders):"]
    with tempfile.TemporaryDirectory() as work:
        bodies = []
        for name in includes():
            lines.append(f"//   sha256 {sha256(name)} {name}")
        for name in sources():
            lines.append(f"//   sha256 {sha256(name)} {name}")
            items = words(compile_one(args.glslang, os.path.join(SHADERS, name), work))
            rows = [", ".join(items[i:i + 8]) for i in range(0, len(items), 8)]
            bodies += ["", f"inline constexpr std::uint32_t {symbol(name)}[] = {{",
                       *[f"    {row}," for row in rows], "};"]
    lines += ["", "#include <cstdint>", "", "namespace mdbridge::render::spirv {", *bodies, "",
              "}  // namespace mdbridge::render::spirv", ""]
    text = "\n".join(lines)
    if args.check:
        with open(HEADER, encoding="utf-8", newline="\n") as fh:
            if fh.read() != text:
                print(f"{os.path.relpath(HEADER, ROOT)} is out of date: run python tools/compile_shaders.py",
                      file=sys.stderr)
                return 1
        print(f"{os.path.relpath(HEADER, ROOT)} is up to date")
        return 0
    with open(HEADER, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(HEADER, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
