"""Compile the 3D view's GLSL shaders to SPIR-V and write them into a C++ header.

    python tools/compile_shaders.py [--glslang PATH]

The header (src/render/shaders/spirv.hpp) is committed, so building MDBridge needs no shader
compiler. It records the SHA-256 of every source; the test "render.shaders_up_to_date"
(cmake/CheckShaders.cmake) fails when a shader changed without running this script again.
Needs glslangValidator (Vulkan SDK, or the glslang-tools / glslang package of a distribution).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, "src", "render", "shaders")
HEADER = os.path.join(SHADERS, "spirv.hpp")
SOURCES = ["placeholder.vert", "placeholder.frag"]  # compiled in this order


def symbol(name: str) -> str:
    stem, stage = name.rsplit(".", 1)
    return "k" + "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]", stem)) + stage.capitalize() + "Spirv"


def compile_one(glslang: str, source: str, work: str) -> bytes:
    out = os.path.join(work, os.path.basename(source) + ".spv")
    subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-o", out, source], check=True,
                   stdout=subprocess.DEVNULL)
    with open(out, "rb") as fh:
        return fh.read()


def words(code: bytes) -> list[str]:
    assert len(code) % 4 == 0, "SPIR-V is a sequence of 32-bit words"
    return [f"0x{int.from_bytes(code[i:i + 4], 'little'):08x}" for i in range(0, len(code), 4)]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--glslang", default=shutil.which("glslangValidator"), help="glslangValidator to use")
    args = parser.parse_args(argv)
    if not args.glslang:
        print("glslangValidator not found (install the Vulkan SDK or glslang-tools)", file=sys.stderr)
        return 1
    version = subprocess.run([args.glslang, "--version"], check=True, capture_output=True,
                             text=True).stdout.splitlines()[0].strip()
    lines = ["#pragma once",
             "// SPIR-V of the 3D view's shaders. Generated by tools/compile_shaders.py; do not edit.",
             f"// {version}, --target-env vulkan1.3",
             "// Sources (cmake/CheckShaders.cmake compares these hashes with the shaders):"]
    with tempfile.TemporaryDirectory() as work:
        bodies = []
        for name in SOURCES:
            path = os.path.join(SHADERS, name)
            with open(path, "rb") as fh:
                digest = hashlib.sha256(fh.read()).hexdigest()
            lines.append(f"//   sha256 {digest} {name}")
            items = words(compile_one(args.glslang, path, work))
            rows = [", ".join(items[i:i + 8]) for i in range(0, len(items), 8)]
            bodies += ["", f"inline constexpr std::uint32_t {symbol(name)}[] = {{",
                       *[f"    {row}," for row in rows], "};"]
    lines += ["", "#include <cstdint>", "", "namespace mdbridge::render::spirv {", *bodies, "",
              "}  // namespace mdbridge::render::spirv", ""]
    with open(HEADER, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(HEADER, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
