"""Write the panel types and layout presets of MDATK's figure as C++ data.

    python3 -I -B tools/gen_panel_tables.py MDATK_CHECKOUT

Imports MDATK (a checkout at v0.0.4.1; nothing is written into it) and dumps
mdatk.render.panels.PANEL_TYPES (registration order: type name, label, description, data kind,
min / max series) and mdatk.render.layout PRESETS / PRESET_LABELS / HEIGHT_RATIOS (grid, slots,
row heights, label; PRESETS' order) into src/core/panel_tables.inc, included by
src/core/panels.cpp (`mdatk list`, the pipeline's panel types, later the renderer). The output is
deterministic; the build needs no Python.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "src", "core", "panel_tables.inc")
WIDTH = 100


def cpp_string(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("".join(f"\\{b:03o}" for b in ch.encode("utf-8")))
    return '"' + "".join(out) + '"'


def wrapped(text: str, indent: int) -> list[str]:
    """A string literal as adjacent literals of at most WIDTH columns (split after spaces)."""
    room = WIDTH - indent - 3
    words, word = [], ""
    for ch in text:
        word += ch
        if ch == " ":
            words.append(word)
            word = ""
    if word:
        words.append(word)
    lines, current = [], ""
    for w in words:
        if current and len(cpp_string(current + w)) > room:
            lines.append(current)
            current = ""
        current += w
    if current or not lines:
        lines.append(current)
    return [" " * indent + cpp_string(line) for line in lines]


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    sys.path.insert(0, os.path.abspath(argv[0]))
    import warnings

    warnings.filterwarnings("ignore")
    from mdatk import __version__
    from mdatk.render.layout import HEIGHT_RATIOS, PRESET_LABELS, PRESETS
    from mdatk.render.panels import PANEL_TYPES

    assert list(PRESET_LABELS) == list(PRESETS), "PRESET_LABELS and PRESETS list other presets"
    lines = [
        "// The panel types and layout presets of MDATK's figure (mdatk/render/panels.py PANEL_TYPES,",
        "// mdatk/render/layout.py PRESETS, PRESET_LABELS, HEIGHT_RATIOS), in MDATK's order.",
        f"// Generated by tools/gen_panel_tables.py from MDATK {__version__}; do not edit.",
        "// Included by src/core/panels.cpp inside its namespace.",
        "",
        "inline constexpr PanelType kPanelTypes[] = {",
    ]
    for name, cls in PANEL_TYPES.items():
        assert cls.type_name == name
        lines.append(f"    {{{cpp_string(name)},")
        for text in (cls.label, cls.description):
            pieces = wrapped(text, 5)
            pieces[-1] += ","
            lines.extend(pieces)
        lines.append(f"     {cpp_string(cls.data_kind)}, {int(cls.min_series)}, {int(cls.max_series)}}},")
    lines += ["};", "", "inline constexpr LayoutSlot kLayoutSlots[] = {"]
    slot = 0
    presets = []
    for name, (rows, cols, slots) in PRESETS.items():
        lines.append(f"    // {name}")
        for r0, r1, c0, c1 in slots:
            lines.append(f"    {{{r0}, {r1}, {c0}, {c1}}},")
        presets.append((name, rows, cols, slot, len(slots)))
        slot += len(slots)
    lines += ["};", "", "inline constexpr double kLayoutHeightRatios[] = {"]
    ratio = 0
    ratios = {}
    for name in PRESETS:
        values = HEIGHT_RATIOS.get(name)
        if values is None:
            continue
        assert len(values) == PRESETS[name][0], name
        lines.append(f"    {', '.join(repr(float(v)) for v in values)},  // {name}")
        ratios[name] = (ratio, len(values))
        ratio += len(values)
    assert set(HEIGHT_RATIOS) <= set(PRESETS)
    lines += ["};", "", "// name, label, rows, cols, first slot, slots, first height ratio, ratios (0: equal rows)",
              "inline constexpr LayoutPresetRow kLayoutPresets[] = {"]
    for name, rows, cols, first, count in presets:
        r_first, r_count = ratios.get(name, (0, 0))
        lines.append(f"    {{{cpp_string(name)}, {cpp_string(PRESET_LABELS[name])}, {rows}, {cols}, {first}, {count}, "
                     f"{r_first}, {r_count}}},")
    lines += ["};", ""]
    for line in lines:
        assert len(line) <= WIDTH, line
    with open(INC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(INC, ROOT)}: {len(PANEL_TYPES)} panel types, {len(PRESETS)} layout presets")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
